/**
 * Business document rules (Phase 6). Pure functions only: no database, no filesystem, no network.
 * File type is decided from the first bytes and the allowed extension, never from the browser-declared type or name.
 */

export const DOC_MAX_BYTES = 10 * 1024 * 1024;
export const DOCUMENT_CATEGORIES = ['RECEIPT', 'INVOICE', 'CONTRACT', 'OTHER'] as const;
export type DocumentCategory = (typeof DOCUMENT_CATEGORIES)[number];
export const LINKED_TYPES = ['SALE', 'EXPENSE', 'PURCHASE', 'SUPPLIER', 'CUSTOMER'] as const;
export type LinkedType = (typeof LINKED_TYPES)[number];
export const DOCUMENT_STATUSES = ['UPLOADED', 'PROCESSING', 'COMPLETED', 'FAILED', 'REVIEW_REQUIRED'] as const;
export type DocumentStatus = (typeof DOCUMENT_STATUSES)[number];

export type DetectedDoc = { ext: string; mime: string; kind: 'image' | 'document' };

const PNG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const ZIP = Buffer.from([0x50, 0x4b, 0x03, 0x04]);

/** Extensions accepted for upload. Must match what apps/ai-service accepts. */
const ALLOWED_EXT: Record<string, { mime: string; kind: 'image' | 'document' }> = {
  pdf: { mime: 'application/pdf', kind: 'document' },
  png: { mime: 'image/png', kind: 'image' },
  jpg: { mime: 'image/jpeg', kind: 'image' },
  jpeg: { mime: 'image/jpeg', kind: 'image' },
  webp: { mime: 'image/webp', kind: 'image' },
  docx: { mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', kind: 'document' },
  xlsx: { mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', kind: 'document' },
  csv: { mime: 'text/csv', kind: 'document' },
  txt: { mime: 'text/plain', kind: 'document' },
  md: { mime: 'text/markdown', kind: 'document' },
};

export function extensionOf(name: string): string {
  const base = name.split(/[\\/]/).pop() ?? '';
  const dot = base.lastIndexOf('.');
  return dot < 0 ? '' : base.slice(dot + 1).toLowerCase();
}

/** Keeps a readable title: basename only, control characters removed, whitespace collapsed, at most 120 characters. */
export function safeTitle(name: string): string {
  const base = (name.split(/[\\/]/).pop() ?? '').replace(/[\u0000-\u001f\u007f]/g, '').replace(/\s+/g, ' ').trim();
  const cleaned = base.replace(/[<>:"|?*]/g, '_').slice(0, 120).trim();
  return cleaned || 'document';
}

/** Storage keys are generated by the server from ids and extensions only. */
export function storageKeyFor(orgId: string, docId: string, ext: string): string {
  return `documents/${orgId}/${docId}.${ext}`;
}

export const SAFE_ID = /^[A-Za-z0-9_-]{1,64}$/;

function looksLikeText(buf: Buffer): boolean {
  const sample = buf.subarray(0, Math.min(buf.length, 4096));
  if (sample.includes(0)) return false;
  try {
    new TextDecoder('utf-8', { fatal: true }).decode(sample);
    return true;
  } catch {
    return false;
  }
}

/**
 * Returns the accepted type, or null. The extension must be allowed AND the bytes must match that extension.
 * Office files are ZIP containers, so they must also contain the part that identifies the format.
 */
export function detectDocument(name: string, buf: Buffer): DetectedDoc | null {
  const ext = extensionOf(name);
  const allowed = ALLOWED_EXT[ext];
  if (!allowed) return null;
  const head = buf.subarray(0, 12);
  switch (ext) {
    case 'pdf':
      return head.subarray(0, 5).toString('ascii') === '%PDF-' ? { ext, ...allowed } : null;
    case 'png':
      return buf.length >= 8 && buf.subarray(0, 8).equals(PNG) ? { ext, ...allowed } : null;
    case 'jpg':
    case 'jpeg':
      return buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff ? { ext, ...allowed } : null;
    case 'webp':
      return head.length >= 12 && head.toString('ascii', 0, 4) === 'RIFF' && head.toString('ascii', 8, 12) === 'WEBP'
        ? { ext, ...allowed }
        : null;
    case 'docx':
      return buf.subarray(0, 4).equals(ZIP) && buf.includes(Buffer.from('word/')) ? { ext, ...allowed } : null;
    case 'xlsx':
      return buf.subarray(0, 4).equals(ZIP) && buf.includes(Buffer.from('xl/')) ? { ext, ...allowed } : null;
    case 'csv':
    case 'txt':
    case 'md':
      return looksLikeText(buf) ? { ext, ...allowed } : null;
    default:
      return null;
  }
}

/** Allowed status changes. Anything else is refused, so a stale request cannot skip a step. */
const TRANSITIONS: Record<DocumentStatus, DocumentStatus[]> = {
  UPLOADED: ['PROCESSING'],
  PROCESSING: ['REVIEW_REQUIRED', 'FAILED'],
  REVIEW_REQUIRED: ['PROCESSING', 'COMPLETED', 'FAILED'],
  FAILED: ['PROCESSING'],
  COMPLETED: [],
};

export function canTransition(from: DocumentStatus, to: DocumentStatus): boolean {
  return TRANSITIONS[from].includes(to);
}

/** Analysis may start only from these states; COMPLETED documents are never re-read by the model. */
export const ANALYZABLE: DocumentStatus[] = ['UPLOADED', 'FAILED', 'REVIEW_REQUIRED'];

export type ExtractedItem = { description: string | null; quantity: string | null; unitPrice: string | null; lineTotal: string | null };
export type ExtractedFields = {
  supplierName: string | null;
  documentNumber: string | null;
  documentDate: string | null;
  currency: string | null;
  subtotal: string | null;
  tax: string | null;
  discount: string | null;
  total: string | null;
  paymentReference: string | null;
  items: ExtractedItem[];
};

const MONEY = /^\d{1,12}(\.\d{1,2})?$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;
const CURRENCY = /^[A-Z]{3}$/;

const text = (v: unknown, max: number): string | null => {
  if (typeof v !== 'string') return null;
  // Control characters are removed; the value is then treated as plain data, never as markup or instructions.
  const t = v.replace(/[\u0000-\u001f\u007f]/g, ' ').replace(/\s+/g, ' ').trim();
  return t ? t.slice(0, max) : null;
};
const money = (v: unknown): string | null => {
  const s = typeof v === 'number' ? String(v) : typeof v === 'string' ? v.replace(/,/g, '').trim() : '';
  return MONEY.test(s) ? s : null;
};

/**
 * Accepts only the expected shape. Anything malformed becomes null ("unknown"), never a guessed value.
 * Unknown keys are dropped.
 */
export function sanitizeExtraction(raw: unknown): ExtractedFields {
  const r: any = raw && typeof raw === 'object' && !Array.isArray(raw) ? raw : {};
  const items: ExtractedItem[] = Array.isArray(r.items)
    ? r.items.slice(0, 100).map((it: any) => ({
        description: text(it?.description, 200),
        quantity: money(it?.quantity),
        unitPrice: money(it?.unitPrice),
        lineTotal: money(it?.lineTotal),
      }))
    : [];
  const date = typeof r.documentDate === 'string' && DATE.test(r.documentDate) ? r.documentDate : null;
  const currency = typeof r.currency === 'string' && CURRENCY.test(r.currency.trim()) ? r.currency.trim() : null;
  return {
    supplierName: text(r.supplierName, 200),
    documentNumber: text(r.documentNumber, 80),
    documentDate: date,
    currency,
    subtotal: money(r.subtotal),
    tax: money(r.tax),
    discount: money(r.discount),
    total: money(r.total),
    paymentReference: text(r.paymentReference, 80),
    items,
  };
}

/** Parses the model's answer. Accepts a bare JSON object, or one wrapped in a code fence. Returns null if neither. */
export function parseModelJson(answer: string): unknown {
  const trimmed = answer.trim().replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/, '').trim();
  try {
    const v = JSON.parse(trimmed);
    return v && typeof v === 'object' && !Array.isArray(v) ? v : null;
  } catch {
    return null;
  }
}
